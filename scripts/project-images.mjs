import { readdirSync, writeFileSync } from 'node:fs';

const dir = 'public/projects';
const out = 'src/data/projectImages.ts';
const extensions = new Set(['png', 'jpg', 'jpeg', 'webp', 'avif']);

let files = [];
try {
  files = readdirSync(dir).sort();
} catch {
  files = [];
}

const map = {};
for (const file of files) {
  const match = /^(.+)\.([a-z0-9]+)$/i.exec(file);
  if (!match || !extensions.has(match[2].toLowerCase())) continue;
  map[match[1]] = `/projects/${file}`;
}

writeFileSync(
  out,
  `// generated by scripts/project-images.mjs
export const projectImages: Record<string, string> = ${JSON.stringify(map, null, 2)};
`,
);

console.log(`project images: ${Object.keys(map).length}`);
